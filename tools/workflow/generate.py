#!/usr/bin/env python3
"""Build-time only: derive shell grammar and guidance from the pinned contract."""
import hashlib
import json
import pathlib
import re
import shlex
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
payload = (ROOT / '.workflow/git-workflow.json').read_bytes()
p = json.loads(payload)
b = json.loads((ROOT / '.workflow/repository.json').read_bytes())
assert p['schema_version'] == b['schema_version'] == 1
assert (p['id'], p['revision']) == (b['policy_id'], b['policy_revision'])
assert re.fullmatch('[a-z][a-z0-9]*', b['issue_key'])
g = p['grammar']
assert all(re.fullmatch('[a-z]+', t) for t in g['types'])
assert all(re.fullmatch(g['maintenance'], r) for r in b['supported_maintenance'])
assert len(set(b['supported_maintenance'])) == len(b['supported_maintenance'])
fields = {'type': '(' + '|'.join(g['types']) + ')', 'issue_key': b['issue_key'],
          'issue_number': g['issue_number'], 'description': g['description']}
topic = '^' + g['topic_template'].format(**fields) + '$'
values = {'TOPIC_RE': topic, 'MAINTENANCE_RE': '^' + g['maintenance'] + '$',
          'TAG_RE': '^' + g['tag'] + '$', 'TRUNK': g['trunk'],
          'SUPPORTED_MAINTENANCE': ' '.join(b['supported_maintenance'])}
outputs = {'.workflow/grammar.sh': '# Generated by tools/workflow/generate.py; do not edit.\n' +
           ''.join(k + '=' + shlex.quote(v) + '\n' for k, v in values.items()),
           '.workflow/policy.sha256': hashlib.sha256(payload).hexdigest() + '  .workflow/git-workflow.json\n'}
text = '# Git workflow\n\nGenerated from `git-workflow.json`; do not edit this view.\n\n'
text += f"Logical contract: `{p['id']}` revision `{p['revision']}`.\n\n"
for title, key in [('Scope', 'scope'), ('Acceptance', 'acceptance'), ('Workflow', 'workflow'), ('Traceability', 'traceability'), ('Enforcement design', 'enforcement_design')]:
    value = p[key]
    text += '## ' + title + '\n\n' + (''.join('- ' + v + '\n' for v in value) if isinstance(value, list) else value + '\n') + '\n'
text += '## Complete grammar and source identity\n\n'
text += 'Source SHA-256: `' + hashlib.sha256(payload).hexdigest() + '`.\n\n'
text += '```json\n' + json.dumps(g, indent=2) + '\n```\n\n'
outputs['.workflow/CONTRACT.md'] = text.rstrip() + '\n'
text += '## Repository binding\n\nIssue key: `' + b['issue_key'] + '`. Supported maintenance lines: ' + (', '.join(b['supported_maintenance']) or 'none') + '.\n\n'
text += 'Topic grammar (POSIX ERE):\n\n```text\n' + topic + '\n```\n\n'
text += 'Maintenance grammar (also requires explicit support binding): `' + g['maintenance'] + '`.\n\nRelease tag grammar: `' + g['tag'] + '`.\n\n'
text += 'See [contribution tooling](../CONTRIBUTING.md) for commands and [activation plan](workflow-enforcement.md) for trust and deployment.\n'
outputs['docs/git-workflow.md'] = text
check = sys.argv[1:] == ['--check']
if sys.argv[1:] not in ([], ['--check']):
    raise SystemExit('usage: generate.py [--check]')
bad = []
for name, content in outputs.items():
    path = ROOT / name
    if check:
        if not path.is_file() or path.read_bytes() != content.encode():
            bad.append(name)
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
if bad:
    raise SystemExit('Generated files differ: ' + ', '.join(bad))
